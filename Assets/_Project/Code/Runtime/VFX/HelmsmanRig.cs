using UnityEngine;
using MaxWorlds.Bosses;
using MaxWorlds.Core;
using MaxWorlds.Rendering;
using MaxWorlds.UI;

namespace MaxWorlds.VFX
{
    /// <summary>
    /// The Helmsman's body (MV-1369, replacing MV-1242's box-on-a-throne): the ship's mind wired into
    /// the Bridge inside its own helm wheel. A 5 m vertical wheel (dark gunmetal, thin cyan neon along
    /// the inner edge) with eight spokes and eight gold-rimmed cyan lens nodes on the rim
    /// (<c>LensNode0..7</c>, clockwise from the top - the beam attacks of the next tickets read them), a
    /// top-heavy rust/teal head at the hub with one huge off-centre gold eye, a hexagonal red core below
    /// it behind two chest plates, a thin gold Curator halo above, three ceiling cables while seated and
    /// four long spindly legs (hip, knee, foot) that fold under the wheel while seated and unfold for
    /// Phase 2. Every mesh is generated by <see cref="CharacterMeshes"/> via <see cref="CharacterPart"/>;
    /// there is no Unity primitive on the character.
    ///
    /// Phase is read straight off <see cref="HelmsmanBoss.IsWalking"/> every tick, never written back.
    /// Legs are posed, not animated: the stepping gait (MV-1132) is driven from the leg transforms
    /// exposed here. <see cref="AuthoredBodyWidth"/> stays the Mothership's a30 boss size (4.5), so the
    /// rig scale resolves to 1 in game and the wheel is a true 5 m.
    /// </summary>
    [DisallowMultipleComponent]
    [PerfSection("rig")]
    public sealed class HelmsmanRig : MonoBehaviour
    {
        public static HelmsmanRig CreateFor(HelmsmanBoss boss)
        {
            if (boss == null) return null;
            var rig = new GameObject("HelmsmanRig").AddComponent<HelmsmanRig>();
            rig.Bind(boss);
            return rig;
        }

        // ---------------------------------------------------------------- dimensions

        private const float AuthoredBodyWidth = 4.5f;

        private const float WheelOuterRadius = 2.5f, WheelInnerRadius = 2.2f, WheelThickness = 0.45f;
        private const int SpokeCount = 8;
        public const int LensNodeCount = 8;
        private const float NodeRimOuter = 0.35f, NodeRimInner = 0.24f, NodeLensDiameter = 0.3f;

        private const float SeatedHubY = 2.7f, WalkingHubY = 4.4f;
        private const float CeilingY = 9f;

        private const float HaloRadius = 1.25f;

        private const int CableCount = 3;

        private const int LegCount = 4;
        private const float LegUpperR0 = 0.14f, LegUpperR1 = 0.10f;
        private const float LegLowerR0 = 0.10f, LegLowerR1 = 0.05f;
        private const float LegKneeBallDiameter = 0.3f;
        private const int LegSegmentSides = 8;

        private static readonly Vector3 EyeAnchor = new Vector3(0.3f, 0.3f, 0.62f);

        // ---------------------------------------------------------------- palette

        private static readonly Color RustColor = new Color(0.66f, 0.34f, 0.15f);
        private static readonly Color TealColor = new Color(0.25f, 0.46f, 0.48f);
        private static readonly Color NearBlackColor = new Color(0.085f, 0.09f, 0.11f);
        private static readonly Color GunmetalColor = new Color(0.16f, 0.18f, 0.22f);
        private static readonly Color LegColor = new Color(0.30f, 0.33f, 0.40f);
        private static readonly Color CoreRedColor = new Color(0.85f, 0.15f, 0.17f);
        private static readonly Color CyanColor = new Color(0.30f, 0.92f, 0.98f);
        private static readonly Color GoldColor = new Color32(0xFF, 0xB0, 0x20, 0xFF);
        private static readonly Color GoldBrightColor = new Color32(0xFF, 0xE0, 0x60, 0xFF);

        private static Material s_rust, s_teal, s_nearBlack, s_gunmetal, s_leg, s_red, s_cyan, s_gold;

        private static void EnsureMaterials()
        {
            if (s_rust != null) return;
            s_rust = NewMaterial("Helmsman_Rust", RustColor);
            s_teal = NewMaterial("Helmsman_Teal", TealColor);
            s_nearBlack = NewMaterial("Helmsman_NearBlack", NearBlackColor);
            s_gunmetal = NewMaterial("Helmsman_Gunmetal", GunmetalColor);
            s_leg = NewMaterial("Helmsman_Leg", LegColor);
            s_red = NewMaterial("Helmsman_CoreRed", CoreRedColor);
            s_cyan = NewMaterial("Helmsman_Cyan", CyanColor);
            s_gold = NewMaterial("Helmsman_Gold", GoldColor);
        }

        private static Material NewMaterial(string name, Color color)
        {
            // No character shader in this build is a look regression, never a magenta one (YT-58).
            var template = MaterialLibrary.Character();
            var m = template != null ? new Material(template) : new Material(MaterialLibrary.SurfaceShader);
            if (m == null) return null;
            m.name = name;
            m.hideFlags = HideFlags.HideAndDontSave;
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor", color);
            if (m.HasProperty("_Color")) m.SetColor("_Color", color);
            return m;
        }

        private static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");

        // ---------------------------------------------------------------- state

        private HelmsmanBoss _boss;
        private MaterialPropertyBlock _mpb;
        private float _rigScale;
        private bool _wasWalking;

        private Transform _bodyRoot;     // origin = wheel hub; wheel, head, eye, core, halo, nodes
        private Transform _cablesRoot;
        private Transform _legsRoot;
        private Transform _coreRoot;
        private Transform _plateLeft, _plateRight;
        private bool _coreExposed;

        private MeshRenderer _eyeLens;
        private readonly MeshRenderer[] _cableRenderers = new MeshRenderer[CableCount];
        private readonly Transform[] _lensNodes = new Transform[LensNodeCount];
        private readonly Leg[] _legs = new Leg[LegCount];

        private sealed class Leg
        {
            public Transform Hip, Upper, Knee, Lower, Foot;
            public Vector3 Sign;
        }

        /// <summary>Wheel + head + halo (everything that rides on the hub) - what the width test measures.</summary>
        public Transform BodyRoot => _bodyRoot;

        /// <summary>LensNode0..7 (clockwise from the top of the wheel) - the beam attacks' emitters.</summary>
        public Transform[] LensNodes => _lensNodes;

        /// <summary>The three ceiling cables - enabled while seated, disabled once torn free.</summary>
        public MeshRenderer[] CableRenderers => _cableRenderers;

        /// <summary>A leg's foot transform, for the stepping gait.</summary>
        public Transform LegFoot(int i) => _legs[i].Foot;

        public bool CoreExposed => _coreExposed;

        public HelmsmanBoss Boss => _boss;

        /// <summary>Ticket 4 opens the chest plates; closed by default.</summary>
        public void SetCoreExposed(bool exposed)
        {
            _coreExposed = exposed;
            float slide = exposed ? 0.75f : 0f;
            if (_plateLeft != null)
                _plateLeft.localPosition = new Vector3(-0.3f - slide, _plateLeft.localPosition.y, _plateLeft.localPosition.z);
            if (_plateRight != null)
                _plateRight.localPosition = new Vector3(0.3f + slide, _plateRight.localPosition.y, _plateRight.localPosition.z);
        }

        private void OnEnable() => HudSignals.BossDefeated += OnDefeated;
        private void OnDisable() => HudSignals.BossDefeated -= OnDefeated;

        private void Bind(HelmsmanBoss boss)
        {
            _boss = boss;
            gameObject.AddComponent<KeepsOwnMaterial>();
            _mpb = new MaterialPropertyBlock();

            var placeholder = _boss.GetComponent<MeshRenderer>();
            if (placeholder != null) placeholder.enabled = false;

            _rigScale = _boss.transform.localScale.x / AuthoredBodyWidth;
            transform.localScale = Vector3.one * _rigScale;

            Build();
            ApplyPhase(force: true);
            Follow();

            _boss.FitColliderTo(RenderedBoundsRelativeTo(_boss.transform, _bodyRoot));
        }

        private void Build()
        {
            EnsureMaterials();
            var bodyGo = new GameObject("Body");
            bodyGo.transform.SetParent(transform, worldPositionStays: false);
            _bodyRoot = bodyGo.transform;

            BuildWheel();
            BuildHead();
            BuildEye();
            BuildCore();
            BuildHalo();
            BuildCables();
            BuildLegs();
        }

        private static Vector3 RimDir(int i)
        {
            float a = i * (360f / SpokeCount) * Mathf.Deg2Rad;   // clockwise from the top, wheel in XY
            return new Vector3(Mathf.Sin(a), Mathf.Cos(a), 0f);
        }

        private static readonly Quaternion Upright = Quaternion.Euler(90f, 0f, 0f);   // flat-in-XZ meshes face +Z

        private void BuildWheel()
        {
            CharacterPart.Add(_bodyRoot, CharacterMeshes.Ring(WheelInnerRadius, WheelOuterRadius, WheelThickness, 48),
                s_gunmetal, Vector3.zero, Upright, Vector3.one, "WheelRim");

            // Thin cyan neon line around the inner edge (a hair thicker than the rim so it shows from the front).
            var neon = CharacterPart.AddLens(_bodyRoot,
                CharacterMeshes.Ring(WheelInnerRadius - 0.06f, WheelInnerRadius + 0.02f, WheelThickness + 0.02f, 48),
                Vector3.zero, Upright, Vector3.one);
            neon.gameObject.name = "WheelNeon";
            ApplyLensColor(neon, CyanColor);

            for (int i = 0; i < SpokeCount; i++)
            {
                Vector3 d = RimDir(i);
                float len = WheelInnerRadius + 0.1f;
                CharacterPart.Add(_bodyRoot, CharacterMeshes.Beam(len, 0.1f, 0.1f, 6), s_gunmetal,
                    d * (len * 0.5f), Quaternion.FromToRotation(Vector3.up, d), Vector3.one, $"Spoke{i}");

                var node = new GameObject($"LensNode{i}").transform;
                node.SetParent(_bodyRoot, worldPositionStays: false);
                node.localPosition = d * ((WheelInnerRadius + WheelOuterRadius) * 0.5f);
                _lensNodes[i] = node;

                CharacterPart.Add(node, CharacterMeshes.Ring(NodeRimInner, NodeRimOuter, 0.14f, 20),
                    s_gold, new Vector3(0f, 0f, WheelThickness * 0.5f), Upright, Vector3.one, "NodeRim");
                var lens = CharacterPart.AddLens(node, CharacterMeshes.Sphere(10),
                    new Vector3(0f, 0f, WheelThickness * 0.5f + 0.02f), Quaternion.identity,
                    Vector3.one * NodeLensDiameter);
                lens.gameObject.name = "NodeLens";
                ApplyLensColor(lens, CyanColor);
            }
        }

        /// <summary>Top-heavy head at the hub: a frustum wider at the top, a rust body with a teal
        /// slab laid across the right on a hard diagonal, a dark cap plate and three status bars.</summary>
        private void BuildHead()
        {
            const float h = 2.0f;
            CharacterPart.Add(_bodyRoot, CharacterMeshes.Prism(4, 1.0f, 1.55f, h), s_rust,
                new Vector3(0f, 0.3f, 0f), Quaternion.identity, new Vector3(1f, 1f, 0.62f), "HeadRust");

            CharacterPart.Add(_bodyRoot, CharacterMeshes.Bevelled(new Vector3(1.0f, 2.1f, 0.1f), 0.03f), s_teal,
                new Vector3(0.62f, 0.3f, 0.57f), Quaternion.Euler(0f, 0f, -14f), Vector3.one, "HeadTeal");

            CharacterPart.Add(_bodyRoot, CharacterMeshes.Bevelled(new Vector3(2.5f, 0.16f, 0.9f), 0.04f), s_nearBlack,
                new Vector3(0f, 0.3f + h * 0.5f + 0.06f, 0f), Quaternion.identity, Vector3.one, "HeadCap");

            Material[] mats = { s_red, s_cyan, s_gold };
            for (int i = 0; i < 3; i++)
                CharacterPart.Add(_bodyRoot, CharacterMeshes.Bevelled(new Vector3(0.55f - i * 0.08f, 0.09f, 0.06f), 0.02f),
                    mats[i], new Vector3(-0.78f, 1.05f - i * 0.2f, 0.62f), Quaternion.identity, Vector3.one, $"StatusBar{i}");
        }

        /// <summary>One huge off-centre gold eye with a thick dark bezel - the brightest thing on the body.</summary>
        private void BuildEye()
        {
            CharacterPart.Add(_bodyRoot, CharacterMeshes.Sphere(16), s_nearBlack, EyeAnchor,
                Quaternion.identity, new Vector3(1.6f, 1.6f, 0.7f), "EyeBezel");

            _eyeLens = CharacterPart.AddLens(_bodyRoot, CharacterMeshes.Sphere(16),
                EyeAnchor + new Vector3(0f, 0f, 0.3f), Quaternion.identity, new Vector3(1.05f, 1.05f, 0.5f));
            _eyeLens.gameObject.name = "EyeLens";
            ApplyLensColor(_eyeLens, GoldColor);
        }

        /// <summary>Hexagonal red core below the head, behind two chest plates (closed by default).</summary>
        private void BuildCore()
        {
            var coreGo = new GameObject("CoreRoot");
            coreGo.transform.SetParent(_bodyRoot, worldPositionStays: false);
            coreGo.transform.localPosition = new Vector3(0f, -1.45f, 0.1f);
            _coreRoot = coreGo.transform;

            CharacterPart.Add(_coreRoot, CharacterMeshes.Prism(6, 0.42f, 0.42f, 0.2f), s_red,
                Vector3.zero, Upright, Vector3.one, "Core");

            var plateSize = new Vector3(0.6f, 0.75f, 0.1f);
            _plateLeft = CharacterPart.Add(_coreRoot, CharacterMeshes.Bevelled(plateSize, 0.03f), s_nearBlack,
                new Vector3(-0.3f, 0f, 0.14f), Quaternion.identity, Vector3.one, "ChestPlateLeft");
            _plateRight = CharacterPart.Add(_coreRoot, CharacterMeshes.Bevelled(plateSize, 0.03f), s_nearBlack,
                new Vector3(0.3f, 0f, 0.14f), Quaternion.identity, Vector3.one, "ChestPlateRight");
        }

        /// <summary>Thin gold halo ring above the wheel - the Curator tell.</summary>
        private void BuildHalo()
        {
            CharacterPart.Add(_bodyRoot, CharacterMeshes.Ring(HaloRadius - 0.05f, HaloRadius, 0.05f, 40), s_gold,
                new Vector3(0f, WheelOuterRadius + 0.55f, 0f), Quaternion.identity, Vector3.one, "CuratorHalo");
        }

        /// <summary>Three ceiling cables to the head's top, seated pose only.</summary>
        private void BuildCables()
        {
            var go = new GameObject("Cables");
            go.transform.SetParent(transform, worldPositionStays: false);
            _cablesRoot = go.transform;

            for (int i = 0; i < CableCount; i++)
            {
                float x = (i - 1) * 0.8f;
                Vector3 from = new Vector3(x * 1.3f, CeilingY, -0.2f);
                Vector3 to = new Vector3(x, SeatedHubY + 1.3f, 0f);
                Vector3 d = to - from;
                Transform cable = CharacterPart.Add(_cablesRoot, CharacterMeshes.Beam(d.magnitude, 0.07f, 0.07f, 6),
                    s_nearBlack, (from + to) * 0.5f, Quaternion.FromToRotation(Vector3.up, d.normalized),
                    Vector3.one, $"Cable{i}");
                _cableRenderers[i] = cable.GetComponent<MeshRenderer>();
            }
        }

        /// <summary>Four spindly articulated legs, built once and posed per phase by <see cref="PoseLegs"/>.</summary>
        private void BuildLegs()
        {
            var go = new GameObject("Legs");
            go.transform.SetParent(transform, worldPositionStays: false);
            _legsRoot = go.transform;

            for (int i = 0; i < LegCount; i++)
            {
                var leg = new Leg { Sign = new Vector3(i % 2 == 0 ? -1f : 1f, 0f, i < 2 ? 1f : -1f) };
                leg.Hip = NewJoint($"Leg{i}Hip");
                leg.Knee = NewJoint($"Leg{i}Knee");
                leg.Foot = NewJoint($"Leg{i}Foot");
                leg.Upper = CharacterPart.Add(_legsRoot, CharacterMeshes.Beam(1f, LegUpperR0, LegUpperR1, LegSegmentSides),
                    s_leg, Vector3.zero, Quaternion.identity, Vector3.one, $"Leg{i}Upper");
                leg.Lower = CharacterPart.Add(_legsRoot, CharacterMeshes.Beam(1f, LegLowerR0, LegLowerR1, LegSegmentSides),
                    s_leg, Vector3.zero, Quaternion.identity, Vector3.one, $"Leg{i}Lower");
                CharacterPart.Add(leg.Knee, CharacterMeshes.Sphere(10), s_rust, Vector3.zero,
                    Quaternion.identity, Vector3.one * LegKneeBallDiameter, "KneeBall");
                CharacterPart.Add(leg.Foot, CharacterMeshes.Prism(8, 0.24f, 0.18f, 0.12f, 0.3f), s_nearBlack,
                    Vector3.zero, Quaternion.identity, Vector3.one, "FootPad");
                _legs[i] = leg;
            }
        }

        private Transform NewJoint(string name)
        {
            var t = new GameObject(name).transform;
            t.SetParent(_legsRoot, worldPositionStays: false);
            return t;
        }

        /// <summary>Folded under the wheel while seated; long, high-kneed and splayed when walking.</summary>
        private void PoseLegs(bool walking)
        {
            float hubY = walking ? WalkingHubY : SeatedHubY;
            for (int i = 0; i < LegCount; i++)
            {
                Leg l = _legs[i];
                Vector3 s = l.Sign;
                Vector3 hip = new Vector3(s.x * 1.1f, hubY - 1.5f, s.z * 0.5f);
                Vector3 knee, foot;
                if (walking)
                {
                    knee = new Vector3(s.x * 2.9f, hubY - 0.6f, s.z * 1.9f);
                    foot = new Vector3(s.x * 3.6f, 0f, s.z * 2.7f);
                }
                else
                {
                    knee = new Vector3(s.x * 1.9f, hubY - 1.9f, s.z * 1.1f);
                    foot = new Vector3(s.x * 1.2f, 0.08f, s.z * 0.8f);
                }
                l.Hip.localPosition = hip;
                l.Knee.localPosition = knee;
                l.Foot.localPosition = foot;
                PlaceBeam(l.Upper, hip, knee);
                PlaceBeam(l.Lower, knee, foot);
            }
        }

        private static void PlaceBeam(Transform beam, Vector3 from, Vector3 to)
        {
            Vector3 d = to - from;
            beam.localPosition = (from + to) * 0.5f;
            beam.localRotation = Quaternion.FromToRotation(Vector3.up, d.normalized);
            beam.localScale = new Vector3(1f, d.magnitude, 1f);   // unit-length beam mesh, stretched
        }

        /// <summary>Same axis-aligned-in-another-frame rebuild as <see cref="SludgequeenRig.RenderedBoundsRelativeTo"/>,
        /// scoped to <paramref name="scopeRoot"/>'s own renderers only.</summary>
        private Bounds RenderedBoundsRelativeTo(Transform reference, Transform scopeRoot)
        {
            var renderers = scopeRoot.GetComponentsInChildren<MeshRenderer>();
            Bounds world = renderers.Length > 0 ? renderers[0].bounds : new Bounds(transform.position, Vector3.one);
            for (int i = 1; i < renderers.Length; i++) world.Encapsulate(renderers[i].bounds);

            Vector3 c = world.center, e = world.extents;
            var local = new Bounds(reference.InverseTransformPoint(c), Vector3.zero);
            for (int xi = -1; xi <= 1; xi += 2)
                for (int yi = -1; yi <= 1; yi += 2)
                    for (int zi = -1; zi <= 1; zi += 2)
                        local.Encapsulate(reference.InverseTransformPoint(c + Vector3.Scale(e, new Vector3(xi, yi, zi))));
            return local;
        }

        private void LateUpdate()
        {
            if (_boss == null) return;
            Tick();
        }

        /// <summary>Everything this rig does once a frame, pulled out of <see cref="LateUpdate"/> so a
        /// test can drive it directly.</summary>
        private void Tick()
        {
            Follow();
            ApplyPhase(force: false);
            UpdateLensGlow();
        }

        private void Follow()
        {
            Vector3 p = _boss.transform.position;
            var at = new Vector3(p.x, 0f, p.z);
            var facing = Quaternion.Euler(0f, _boss.transform.eulerAngles.y, 0f);
            transform.SetPositionAndRotation(at, facing);
        }

        /// <summary>Reads <see cref="HelmsmanBoss.IsWalking"/> and never writes it back.</summary>
        private void ApplyPhase(bool force)
        {
            bool walking = _boss != null && _boss.IsWalking;
            if (!force && walking == _wasWalking) return;
            _wasWalking = walking;

            _cablesRoot.gameObject.SetActive(!walking);
            for (int i = 0; i < _cableRenderers.Length; i++)
                if (_cableRenderers[i] != null) _cableRenderers[i].enabled = !walking;

            _bodyRoot.localPosition = new Vector3(0f, walking ? WalkingHubY : SeatedHubY, 0f);
            PoseLegs(walking);
        }

        private void UpdateLensGlow()
        {
            if (_eyeLens == null) return;
            ApplyLensColor(_eyeLens, _boss.LensTelling ? GoldBrightColor : GoldColor);
        }

        private void ApplyLensColor(MeshRenderer r, Color c)
        {
            if (r == null) return;
            c.a = 1f;
            r.GetPropertyBlock(_mpb);
            _mpb.SetColor(BaseColorId, c);
            r.SetPropertyBlock(_mpb);
        }

        private void OnDefeated()
        {
            // Same MV-625 guard every other boss rig's own OnDefeated uses.
            if (_boss == null || !_boss.IsDead) return;
            gameObject.SetActive(false);
        }
    }
}
